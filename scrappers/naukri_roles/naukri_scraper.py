def real_company(job):
    """The displayed hiring entity. For consultant postings that don't hide the
    client, prefer the client name; else the posting company."""
    company = (job.get("companyName") or "").strip()
    if job.get("consultant") and not job.get("hideClientName"):
        client = (job.get("clientTitleString") or job.get("hiringFor") or "").strip()
        if client:
            return company, client       # (recruiter, client)
    return company, ""


def job_to_rich_row(job):
    """Build one rich-CSV row from a captured jobDetails card.

    Returns None when the shared classifier rules the job out of scope
    (the caller counts it as excluded_out_of_scope and drops it).
    """
    title = (job.get("title") or "").strip()
    company, hiring_for = real_company(job)
    city, country, code, dial = parse_location(placeholder(job, "location"))
    verdict = classify_job(
        title,
        job.get("tagsAndSkills") or "",
        strip_html(job.get("jobDescription") or ""))
    if not verdict["in_scope"]:
        return None
    salary_raw, sal_min, sal_max, sal_cur, sal_per = parse_salary(job)
    jd_url = (job.get("jdURL") or "").strip()
    if jd_url.startswith("/"):
        jd_url = SITE_BASE + jd_url

    return {
        "source": SITE,
        "job_id": str(job.get("jobId") or ""),
        "title": title,
        "company": company,
        "company_id": str(job.get("companyId") or ""),
        "hiring_for": hiring_for,
        "city": city,
        "country": country,
        "country_code": code,
        "country_dial_code": dial,
        "salary_raw": salary_raw,
        "salary_min": sal_min,
        "salary_max": sal_max,
        "salary_currency": sal_cur,
        "salary_period": sal_per,
        "experience_min_years": _exp_int(job.get("minimumExperience")),
        "experience_max_years": _exp_int(job.get("maximumExperience")),
        "job_type": map_job_type(job),
        "category": verdict["category"],
        "sub_category": verdict["sub_category"],
        "sub_category_basis": verdict["sub_category_basis"],
        "role_family": verdict["role_family"],
        "company_type": classify_company_type(company, hiring_for),
        "role_category_gid": str(job.get("roleCategoryGid") or ""),
        "tags_and_skills": (job.get("tagsAndSkills") or "").strip(),
        "vacancies": str(job.get("vacancy") or ""),
        "company_logo": (job.get("logoPathV3") or job.get("logoPath") or "").strip(),
        "posted_date": epoch_ms_to_date(job.get("createdDate")),
        "description": strip_html(job.get("jobDescription") or "")[:DESCRIPTION_MAX_CHARS],
        "job_url": jd_url,
        "scraped_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "needs_review": "true" if verdict["needs_review"] else "false",
        "all_families": verdict["all_families"],
        "family_scores": verdict["family_scores"],
        "family_confidence": verdict["family_confidence"],
        "matched_in": verdict["matched_in"],
    }


def _clean(value):
    if value is None or (isinstance(value, float) and pd.isna(value)):
        return ""
    text = str(value).strip()
    return "" if text.lower() == "nan" else text


def rich_row_to_club_row(r):
    """Map a rich row to the 23-column HealthCareers.club schema.

    The club salary_currency enum only allows INR/USD, so salary is exported
    only when the source currency matches AND the pay period is known;
    otherwise those columns stay empty (the rich CSV keeps the raw values).
    """
    currency = _clean(r.get("salary_currency")).upper()
    period = _clean(r.get("salary_period"))
    lo, hi = _clean(r.get("salary_min")), _clean(r.get("salary_max"))
    exportable = bool(lo) and currency in ("INR", "USD") and period != ""
    return {
        "country_name": _clean(r.get("country")) or "India",
        "country_code": _clean(r.get("country_code")) or "IN",
        "country_dial_code": _clean(r.get("country_dial_code")) or "+91",
        "city_name": _clean(r.get("city")) or _clean(r.get("country")) or "India",
        "company_name": _clean(r.get("company")),
        "company_type": _clean(r.get("company_type")) or "hospital",
        "company_logo": _clean(r.get("company_logo")),
        "company_about": "",
        "title": _clean(r.get("title")),
        "description": _clean(r.get("description")),
        "job_type": _clean(r.get("job_type")) or "full_time",
        "category": _clean(r.get("category")),
        "sub_category": _clean(r.get("sub_category")),
        "role_family": _clean(r.get("role_family")),
        "application_url": _clean(r.get("job_url")),
        "posted_at": _clean(r.get("posted_date")),
        "min_experience": _clean(r.get("experience_min_years")),
        "max_experience": _clean(r.get("experience_max_years")),
        # naukri cards carry no structured qualification field, so this is
        # always grounded extraction from the description (never inferred).
        "qualification": extract_qualification(_clean(r.get("description"))),
        "min_salary": lo if exportable else "",
        "max_salary": (hi or lo) if exportable else "",
        "salary_period": period if exportable else "",
        "salary_currency": currency if exportable else "",
    }


# ----------------------------------------------------------------------------
# Time window
# ----------------------------------------------------------------------------

def compute_cutoff(existing_df, today=None):
    """First run: today - INITIAL_WINDOW_DAYS. Later: newest stored posted_date
    minus WATERMARK_GRACE_DAYS of overlap (dedup absorbs it)."""
    if existing_df is not None and "posted_date" in existing_df.columns:
        dates = pd.to_datetime(existing_df["posted_date"], errors="coerce").dropna()
        if not dates.empty:
            return (dates.max() - pd.Timedelta(days=WATERMARK_GRACE_DAYS)).date().isoformat()
    today = today or date.today()
    return (today - timedelta(days=INITIAL_WINDOW_DAYS)).isoformat()


