#!/usr/bin/env python3
"""Scrape healthcare job listings from naukri.com.

Data source
-----------
naukri.com is a client-rendered Next.js SPA backed by a private JSON API:

    GET https://www.naukri.com/jobapi/v3/search
        ?noOfResults=20&urlType=search_by_keyword&searchType=adv
        &keyword=healthcare and life sciences&pageNo=<N>&sort=f
        &seoKey=healthcare-and-life-sciences-jobs[-N]
    -> {"noOfJobs": 41073, "jobDetails": [ {...}, ... ], "clusters": {...}}

The listing is filtered at the source to the **Healthcare & Life Sciences**
functional area (the `/healthcare-and-life-sciences-jobs` SEO page, ~41k jobs)
and sorted by freshness (`sort=f`, newest first), which lets us stop paginating
once a page is older than the cutoff.

Each jobDetails item carries everything we need directly on the card — no
detail-page fetch required:
    jobId, title, companyName, companyId, currency, createdDate (epoch **ms**),
    jdURL (relative), placeholders[{type: experience|salary|location}],
    salaryDetail{minimumSalary, maximumSalary, currency, hideSalary},
    minimumExperience, maximumExperience, tagsAndSkills, jobDescription (short),
    roleCategoryGid, consultant, hiringFor, clientTitleString, logoPathV3.

Why browser-captured JSON (not live HTTP)
-----------------------------------------
The `/jobapi/v3/search` endpoint requires a per-request signed `nkparam`
header generated by the site's own JavaScript; requests without it return
HTTP 406 {"message": "recaptcha required"}. The whole site also sits behind
Akamai, which resets non-browser TLS fingerprints. So — exactly like this
repo's `indeed/` scraper — the responses are captured in a real browser
(paging through the date-sorted listing while a fetch/XHR interceptor
accumulates `jobDetails`), dumped to `captures/<DD-MM-YYYY>.json`, and this
scraper consumes that JSON offline. See README.md for the capture recipe.

robots.txt (checked against the saved capture, honored per master-spec §7):
the `User-agent: *` group does NOT disallow the healthcare listing or
`/jobapi/`; only recruiter/admin paths are blocked. naukri additionally
disallows automated AI crawlers (`claudebot`, `gptbot`, …) from `/` — we do
not crawl as a bot; a human drives the browser capture, and this script only
transforms the already-captured JSON.

Salary (master spec §3: capture, don't filter)
----------------------------------------------
naukri salaries are INR per annum. `salaryDetail` holds the full integer
range (e.g. 4,500,000); the card's salary placeholder ("45-60 Lacs PA") is
kept verbatim as salary_raw. Undisclosed -> "Not Disclosed", numeric fields
empty. Never filtered on, never invented.

Classification (taxonomy-migration-spec, 2026-08-25)
----------------------------------------------------
Every candidate card goes through the shared two-level classifier
(_shared/classification.py :: classify_job): out-of-scope cards are dropped
and counted as excluded_out_of_scope; in-scope cards get `category`
("Non Clinical" | "Public Health"), `sub_category`, and the role_family /
score trace columns in the rich CSV. needs_review rows are kept AND appended
to needs_review.csv.

Outputs (per the repo README + master-scraper-spec.md)
------------------------------------------------------
* naukri_roles_jobs.csv      — rich cumulative store (dedup key: job_id),
                               source of truth for the incremental watermark.
* ../../jobs_csv/<DD-MM-YYYY>/naukri_roles.csv
                             — the same jobs mapped to the shared
                               HealthCareers.club 23-column schema
                               (CLUB_COLUMNS from _shared/classification.py).
* needs_review.csv           — in-scope titles flagged by the classifier.

Time window: first run keeps jobs posted in the last INITIAL_WINDOW_DAYS (2)
(7); later runs keep only jobs newer than the newest stored posted_date
minus WATERMARK_GRACE_DAYS of overlap (dedup absorbs the overlap).

Run `python naukri_scraper.py --help` for options.
"""

