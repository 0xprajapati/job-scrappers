_TAG_RE = re.compile(r"<[^>]+>")


def strip_html(text):
    """HTML / multiline card text -> readable single-spaced text."""
    text = re.sub(r"</?(p|br|li|ul|ol|div|h\d)[^>]*>", " ", text or "",
                  flags=re.IGNORECASE)
    text = _TAG_RE.sub("", text)
    text = html_lib.unescape(text)
    return re.sub(r"\s+", " ", text).strip()


def epoch_ms_to_date(epoch_ms):
    """Unix epoch in MILLISECONDS -> "YYYY-MM-DD" (UTC), or "" if unparseable.

    naukri stamps createdDate in ms; 0/None (a handful of cards) -> "".
    """
    try:
        ms = int(epoch_ms)
    except (TypeError, ValueError):
        return ""
    if ms <= 0:
        return ""
    try:
        return datetime.fromtimestamp(ms / 1000, tz=timezone.utc).date().isoformat()
    except (ValueError, OSError, OverflowError):
        return ""


def placeholder(job, kind):
    """Return the label of the placeholder of the given type, or ""."""
    for p in job.get("placeholders") or []:
        if p.get("type") == kind:
            return (p.get("label") or "").strip()
    return ""


_CITY_ALL_AREAS_RE = re.compile(r"\s*\(all areas\)\s*", re.IGNORECASE)


def parse_location(location):
    """Split a naukri location placeholder into (city, country_name, code, dial).

    Formats seen: "Hyderabad", "Nashik, Pune, Mumbai (All Areas)" (multi-city
    -> take the first), "Saudi Arabia" (a bare country). Unknown -> India.
    """
    location = (location or "").strip()
    if not location:
        return ("", "India", "IN", "+91")
    first = location.split(",")[0].strip()
    first = _CITY_ALL_AREAS_RE.sub("", first).strip()

    # A bare country name as the whole location (overseas postings).
    meta = COUNTRY_META.get(location.lower()) or COUNTRY_META.get(first.lower())
    if meta and first.lower() in COUNTRY_META:
        # location itself names a country -> no city given; use the country
        # name as the city too (club requires city_name non-empty), matching
        # the naukrigulf "Qatar -> Qatar" convention.
        name, code, dial = meta
        return (name, name, code, dial)
    if meta:
        name, code, dial = meta
        return (first, name, code, dial)
    # Default: an Indian city.
    return (first, "India", "IN", "+91")


def parse_salary(job):
    """Return (salary_raw, min_int, max_int, currency, period).

    naukri salaries are INR per annum. `salaryDetail` holds full integers;
    the salary placeholder ("45-60 Lacs PA") is the verbatim display. Hidden
    / absent -> ("Not Disclosed", "", "", "", "").
    """
    raw = placeholder(job, "salary") or ""
    detail = job.get("salaryDetail") or {}
    if not detail or detail.get("hideSalary"):
        return (raw or "Not Disclosed", "", "", "", "")
    lo = detail.get("minimumSalary")
    hi = detail.get("maximumSalary")
    try:
        lo = int(round(float(lo))) if lo not in (None, "") else None
        hi = int(round(float(hi))) if hi not in (None, "") else None
    except (TypeError, ValueError):
        lo = hi = None
    if not lo and not hi:
        return (raw or "Not Disclosed", "", "", "", "")
    if lo and hi and hi < lo:
        lo, hi = hi, lo
    lo = lo or hi
    hi = hi or lo
    currency = (detail.get("currency") or job.get("currency") or "INR").upper()
    # naukri displays annual figures ("... PA"); default per_annum.
    period = "per_month" if re.search(r"\bp\.?m\b|month", raw, re.IGNORECASE) \
        else "per_annum"
    return (raw or "Not Disclosed", str(lo), str(hi), currency, period)


def _exp_int(value):
    try:
        return str(int(float(value)))
    except (TypeError, ValueError):
        return ""


# All keep/drop and category labeling is classify_job's alone
# (_shared/classification.py) — no per-scraper classification lists here.
_PHARMA_COMPANY_RE = re.compile(
    r"pharma|therapeut|laborator|\blabs?\b|\bcro\b|biotech|life ?science|"
    r"diagnostic|clinical research|medical devices?|healthcare it|"
    r"health informatics", re.IGNORECASE)


def classify_company_type(name, hiring_for=""):
    """club company_type enum: hospital | pharma (default hospital)."""
    text = "{} {}".format(name or "", hiring_for or "")
    return "pharma" if _PHARMA_COMPANY_RE.search(text) else "hospital"


def map_job_type(job):
    """club job_type enum. naukri cards rarely mark WFH on the listing; use the
    title/tags and jobType hint, defaulting to full_time."""
    text = " ".join(str(job.get(k) or "") for k in
                    ("title", "tagsAndSkills", "jobType")).lower()
    if "work from home" in text or "wfh" in text or "remote" in text:
        return "remote"
    if "hybrid" in text:
        return "hybrid"
    if "part time" in text or "part-time" in text:
        return "part_time"
    return "full_time"


