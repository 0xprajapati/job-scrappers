def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Scrape healthcare jobs from a naukri.com browser capture.")
    parser.add_argument("--from-json", dest="from_json", default=None,
                        metavar="FILE",
                        help="capture JSON to ingest (default: newest in "
                             "captures/)")
    parser.add_argument("--output", default=RICH_CSV,
                        help="rich cumulative CSV path (default: %(default)s)")
    parser.add_argument("--limit", type=int, default=None, metavar="N",
                        help="stop after N new jobs (for test runs)")
    parser.add_argument("--run-date", default=date.today().strftime("%d-%m-%Y"),
                        help="jobs_csv/<DD-MM-YYYY>/ folder (default: today)")
    parser.add_argument("--verbose", action="store_true", help="debug logging")
    args = parser.parse_args(argv)

    logging.basicConfig(
        level=logging.DEBUG if args.verbose else logging.INFO,
        format="%(asctime)s %(levelname)s %(message)s", datefmt="%H:%M:%S")

    capture_path = args.from_json or latest_capture()
    if not capture_path or not Path(capture_path).exists():
        parser.error("no capture JSON found — pass --from-json <file> "
                     "(see README for the browser-capture recipe)")
    cards = load_capture(capture_path)
    log.info("Loaded %d unique cards from %s", len(cards), capture_path)

    existing_df = load_existing(args.output)
    known_ids = set(existing_df["job_id"].dropna()) if existing_df is not None else set()
    cutoff = compute_cutoff(existing_df)
    log.info("Existing CSV has %d known jobs; keeping jobs posted on/after %s",
             len(known_ids), cutoff)

    counters = {"scanned": 0, "excluded_old": 0, "excluded_out_of_scope": 0,
                "needs_review": 0,
                "new": 0, "duplicates": 0}
    new_rows, review_log = [], []

    for job in cards:
        counters["scanned"] += 1
        try:
            job_id = str(job.get("jobId") or "")
            posted = epoch_ms_to_date(job.get("createdDate"))
            if not (posted and posted >= cutoff):
                counters["excluded_old"] += 1
                continue
            if job_id in known_ids:
                counters["duplicates"] += 1
                continue
            row = job_to_rich_row(job)
            if row is None:
                counters["excluded_out_of_scope"] += 1
                continue
        except Exception as exc:  # never let one card crash the run
            log.warning("Skipping malformed card %s: %s", job.get("jobId"), exc)
            continue

        if row["needs_review"] == "true":
            counters["needs_review"] += 1
            review_log.append({"job_id": row["job_id"], "title": row["title"],
                               "company": row["company"]})
        known_ids.add(row["job_id"])
        new_rows.append(row)
        counters["new"] += 1
        if args.limit is not None and counters["new"] >= args.limit:
            break

    # ---- write rich cumulative CSV (source of truth) ----
    if new_rows:
        new_df = pd.DataFrame(new_rows, dtype=str)
        combined = (pd.concat([existing_df, new_df], ignore_index=True)
                    if existing_df is not None else new_df)
        combined = combined.drop_duplicates(subset="job_id", keep="first")
        for col in RICH_COLUMNS:
            if col not in combined.columns:
                combined[col] = ""
        combined = combined[RICH_COLUMNS]
        combined.to_csv(args.output, index=False)
        log.info("Wrote %s (%d total rows)", args.output, len(combined))
    else:
        combined = existing_df if existing_df is not None else pd.DataFrame(columns=RICH_COLUMNS)
        log.info("No new jobs; %s left unchanged", args.output)

    # ---- always (re)write the club-schema CSV for this run date ----
    if len(combined):
        target, n = write_club_csv(combined, args.run_date)
        log.info("Wrote %s (%d rows, HealthCareers.club schema)", target, n)

    if review_log:
        review_df = pd.DataFrame(review_log, dtype=str)
        try:
            old_review = pd.read_csv(NEEDS_REVIEW_CSV, dtype=str)
            review_df = pd.concat([old_review, review_df], ignore_index=True)
        except FileNotFoundError:
            pass
        review_df = review_df.drop_duplicates(subset="job_id", keep="first")
        review_df.to_csv(NEEDS_REVIEW_CSV, index=False)
        log.info("Wrote %s (%d titles to review)", NEEDS_REVIEW_CSV, len(review_df))

    print("\n===== Run summary =====")
    print("Cards scanned:            {:>5,}".format(counters["scanned"]))
    print("Excluded (older than {}): {:>3,}".format(cutoff, counters["excluded_old"]))
