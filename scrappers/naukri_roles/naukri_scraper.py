def load_capture(path):
    """Load a browser capture: either a bare JSON array of jobDetails cards, or
    a full search-API response ({"jobDetails": [...]}), or a list of such
    responses. Returns a de-duplicated list of card dicts."""
    with open(path, encoding="utf-8") as fh:
        data = json.load(fh)

    cards = []
    if isinstance(data, dict):
        cards = data.get("jobDetails") or []
    elif isinstance(data, list):
        if data and isinstance(data[0], dict) and "jobDetails" in data[0]:
            for page in data:
                cards.extend(page.get("jobDetails") or [])
        else:
            cards = data
    by_id = {}
    for c in cards:
        jid = str(c.get("jobId") or "")
        if jid:
            by_id.setdefault(jid, c)
    return list(by_id.values())


def latest_capture():
    """Newest captures/<DD-MM-YYYY>.json by embedded date, or None."""
    if not CAPTURES_DIR.exists():
        return None
    candidates = sorted(CAPTURES_DIR.glob("*.json"))
    return str(candidates[-1]) if candidates else None


def load_existing(path):
    try:
        return pd.read_csv(path, dtype=str)
    except FileNotFoundError:
        return None


def write_club_csv(rich_df, run_date):
    club_rows = [rich_row_to_club_row(r) for _, r in rich_df.iterrows()]
    club_df = pd.DataFrame(club_rows, columns=CLUB_COLUMNS)
    out_dir = CLUB_CSV_DIR / run_date
    out_dir.mkdir(parents=True, exist_ok=True)
    target = out_dir / "{}.csv".format(SITE)
    club_df.to_csv(target, index=False)
    return target, len(club_df)


